#!/usr/bin/env python3
"""Build the read-only v11 ramdisk (serial TP510-RAM-V11RO) for bisect candidate B2; no phone access.

kernel-upgrade/diagnostic-probe-v11-ro/init.c is v11's init.c with the userdata write test cut out
and a new serial. The v11 sources stay as they are, because v11's gates pin their hashes.
--write regenerates that file from v11's. The default run checks the file still equals what the
transform gives, compiles it with build-upgrade-ramdisk.py, rebuilds v11's own init with the default
flags and compares it with the shipped one, and runs the write check on the source and the binary.
--self-test shows the write check refusing sources and binaries that write.
"""
import pocket_paths
import argparse
import hashlib
import json
import os
import re
import runpy
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BULK = pocket_paths.build_root()
V11_DIR = ROOT / 'kernel-upgrade/diagnostic-probe-v11'
RO_DIR = ROOT / 'kernel-upgrade/diagnostic-probe-v11-ro'
V11_RAMDISK = BULK / 'artifacts/diagnostic-5.10-v11/ramdisk'
OUT = BULK / 'artifacts/bisect-v2/ramdisk-v11ro'
EVIDENCE = ROOT / 'evidence/kernel-upgrade/diagnostic-ramdisk-v11ro.json'
LABEL = 'TP510-RAM-V11RO'
SOURCES = [ROOT / 'kernel-upgrade/ram-probe/ufs-readonly.h', ROOT / 'kernel-upgrade/tkcore-probe/feature_query.h',
           V11_DIR / 'probes.h']
BUILD = runpy.run_path(str(ROOT / 'tools/build-upgrade-ramdisk.py'))['build']


class Refused(Exception):
    pass


def sha(data):
    return hashlib.sha256(data).hexdigest()


def once(text, old, new):
    if text.count(old) != 1:
        raise Refused('expected exactly one: %r' % old[:60])
    return text.replace(old, new)


def transform(text):
    """v11 init.c without the userdata write test and with the RO serial."""
    text = once(text, '#define PROBE_LABEL "TP510-RAM-V11"', '#define PROBE_LABEL "%s"' % LABEL)
    text = once(text, '#define PROBE_PRODUCT "Titan Pocket 5.10 RAM diagnostic v11"',
                '#define PROBE_PRODUCT "Titan Pocket 5.10 RAM diagnostic v11 read-only"')
    text = once(text, '#include "probes.h"', '// probes.h has the write test steps; nothing here calls them, so they are not linked.\n'
                '#pragma clang diagnostic ignored "-Wunused-function"\n#include "../diagnostic-probe-v11/probes.h"')
    # The pwritev2 wrapper and the whole userdata write test, up to the super mount test.
    start = text.index('// pwritev2 is API 33')
    end = text.index('// Validates kernel partition')
    text = text[:start] + text[end:]
    start = text.index('// ---- Userdata write test ----')
    end = text.index('// ---- Super read-only dm-linear mount test ----')
    text = text[:start] + text[end:]
    text = once(text, '''    if (userdata) userdata_write_test(disk, userdata, lbs, controller);
    else report("userdata-write userdata not in GPT; no write");''',
                '''    (void)userdata;
    report("userdata-write not in this build; no write");''')
    header = ('// Generated by tools/build-pocket-v11ro-ramdisk.py from ../diagnostic-probe-v11/init.c: the userdata\n'
              '// write test is cut out, so this init opens no block device for writing. Serial %s.\n' % LABEL)
    return header + text


def strip_comments(text):
    return re.sub(r'//[^\n]*', '', text)


# Writable opens the read-only build may keep: console, ACM tty, watchdog, kmsg, and the sysfs and
# configfs attribute writes (open(path, O_WRONLY ...) in ram-probe/init.c).
WRITE_OK = ('/dev/console', '/dev/ttyGS0', '/dev/watchdog0', '/dev/kmsg', 'open(path, O_WRONLY | O_CLOEXEC)')


def check_source(text):
    """Problems: any block-device write path in the (comment-stripped) source text."""
    problems = []
    code = strip_comments(text)
    for pattern, message in [(r'\bpwrite(64|v|v2)?\b|pwritev2|__NR_pwrite', 'pwrite call'),
                             (r'\btp10_write_test\s*\(', 'write test called'),
                             (r'\bRWF_', 'RWF write flag'),
                             (r'MS_REMOUNT|\bBLKROSET\s*,\s*&rw', 'remount or writable block ioctl')]:
        if re.search(pattern, code):
            problems.append(message)
    for line in code.splitlines():
        if re.search(r'O_RDWR|O_WRONLY|O_CREAT|O_TRUNC', line) and not any(ok in line for ok in WRITE_OK):
            problems.append('writable open: ' + line.strip()[:80])
    return sorted(set(problems))


def check_binary(binary):
    problems = []
    # Static bionic carries pwrite itself, so only the write test's own strings say it was linked in.
    for needle in [b'userdata-write step', b'userdata-write node=', b'userdata-write open', b'RWF_DSYNC']:
        if needle in binary:
            problems.append('binary contains ' + needle.decode())
    return problems


def source_texts():
    # probes.h holds the generic write-test steps; they are static and only linked in if init.c calls them,
    # which the source check and the binary check both look for.
    return (RO_DIR / 'init.c').read_text() + '\n' + '\n'.join(
        p.read_text() for p in SOURCES[:2] + [ROOT / 'kernel-upgrade/ram-probe/init.c', ROOT / 'kernel-upgrade/ram-probe/commands.h'])


def self_test():
    cases = []
    good = source_texts()
    v11 = (V11_DIR / 'init.c').read_text() + good
    mutations = [
        ('v11 source itself (has the write test)', v11, False),
        ('RO source as built', good, True),
        ('pwrite added', good + '\nstatic void a(int f) { pwrite(f, "", 1, 0); }\n', False),
        ('pwritev2 syscall added', good + '\nstatic long b(void) { return syscall(__NR_pwritev2); }\n', False),
        ('O_RDWR open of a node', good + '\nstatic int c(const char *n) { return open(n, O_RDWR); }\n', False),
        ('O_WRONLY open of a node', good + '\nstatic int d(const char *n) { return open(n, O_WRONLY); }\n', False),
        ('write test called', good + '\nstatic void e(void) { tp10_write_test(0, 0, 0, 0, 0); }\n', False),
        ('remount', good + '\nstatic void f(void) { mount("a", "b", "ext4", MS_REMOUNT, 0); }\n', False)]
    for label, text, expect in mutations:
        problems = check_source(text)
        cases.append({'case': label, 'expect_accept': expect, 'accepted': not problems, 'reason': '; '.join(problems)[:200],
                      'pass': (not problems) == expect})
    for label, binary, expect in [('binary with the write test strings', b'..userdata-write step1 ..', False),
                                  ('binary with the write test node line', b'..userdata-write node=%s..', False), ('clean binary', b'..hash..', True)]:
        problems = check_binary(binary)
        cases.append({'case': label, 'expect_accept': expect, 'accepted': not problems, 'reason': '; '.join(problems),
                      'pass': (not problems) == expect})
    failed = [c for c in cases if not c['pass']]
    if failed:
        raise Refused('self-test: %s' % failed)
    return {'cases': cases, 'passed': len(cases)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--write', action='store_true', help='regenerate kernel-upgrade/diagnostic-probe-v11-ro/init.c')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()
    try:
        generated = transform((V11_DIR / 'init.c').read_text())
        if args.write:
            RO_DIR.mkdir(exist_ok=True)
            (RO_DIR / 'init.c').write_text(generated)
        if (RO_DIR / 'init.c').read_text() != generated:
            raise Refused('%s is not the transform of v11 init.c; run with --write' % (RO_DIR / 'init.c'))
        test = self_test()
        if args.self_test:
            for c in test['cases']:
                print('%-4s %s%s' % ('ok' if c['pass'] else 'FAIL', c['case'], ' (' + c['reason'] + ')' if c['reason'] else ''))
            print('self-test: %d cases' % test['passed'])
            return
        problems = check_source(source_texts())
        if problems:
            raise Refused('RO source: ' + '; '.join(problems))
        with tempfile.TemporaryDirectory(dir=BULK / 'artifacts') as tmp:
            tmp = Path(tmp)
            # v11's own build with the default flags must give the shipped init.
            BUILD(V11_DIR / 'init.c', tmp / 'v11', tmp / 'v11.json', extra_sources=SOURCES)
            shipped = (V11_RAMDISK / 'init').read_bytes()
            rebuilt = (tmp / 'v11/init').read_bytes()
            if rebuilt != shipped or (tmp / 'v11/ramdisk.cpio.gz').read_bytes() != (V11_RAMDISK / 'ramdisk.cpio.gz').read_bytes():
                raise Refused('rebuilding v11 does not give the shipped init and ramdisk')
        if (OUT / 'init').exists():
            raise Refused('%s exists; refusing to overwrite' % (OUT / 'init'))
        record = BUILD(RO_DIR / 'init.c', OUT, EVIDENCE, extra_sources=SOURCES)
        binary = (OUT / 'init').read_bytes()
        problems = check_binary(binary)
        if problems:
            raise Refused('RO binary: ' + '; '.join(problems))
        if LABEL.encode() not in binary:
            raise Refused('RO binary lacks serial ' + LABEL)
        record.update({'serial': LABEL, 'v11_default_rebuild_identical': True, 'v11_init_sha256': sha(shipped),
                       'v11_ramdisk_gz_sha256': sha((V11_RAMDISK / 'ramdisk.cpio.gz').read_bytes()),
                       'write_check': {'source': 'no pwrite, write test or writable block-device open',
                                       'binary': 'none of the write test strings'},
                       'self_test': test, 'tool_sha256': sha(Path(__file__).read_bytes())})
        EVIDENCE.write_text(json.dumps(record, indent=2) + '\n')
        print('v11 default rebuild identical to shipped init', sha(shipped))
        print('RO ramdisk.cpio.gz', sha((OUT / 'ramdisk.cpio.gz').read_bytes()), '; self-test %d cases' % test['passed'])
    except Refused as e:
        print('refused: ' + str(e), file=sys.stderr)
        sys.exit(2)


if __name__ == '__main__':
    main()
