#!/usr/bin/env python3
"""Write the OZ8806 driver's NTC table (drivers/power/supply/oz8806_ntc.h) from the Beta formula.

The cell thermistor is a 10 kOhm NTC to ground, read through a pull-up to the gauge's
1.8 V reference: R = mV * pullup / (1800 - mV), pull-up 24 kOhm (hw_ver GPIO 5 reads 1)
or 120 kOhm. The table maps R (Ohm) to temperature (C), 5 C apart from -25 to 115 C.

R(T) = R_NOM * exp(BETA * (1/T - 1/T_NOM)), T in kelvin. BETA = 3312 K with 10 kOhm at
22 C is the least-squares fit to the curve the stock gauge uses, over -23 to 62 C: the
largest error there is 0.07 C. That is the same as a 10 kOhm (25 C) NTC read 3 C low.
Above 62 C the stock curve has a bad point at 107 C (2.6 C off); the formula is used as is.

  python3 tools/make-pocket-oz8806-ntc.py          write the header
  python3 tools/make-pocket-oz8806-ntc.py --check  exit 1 if the header differs
"""
import argparse, math, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'tools/kernel-source/upgrade-5.10/drivers/power/supply/oz8806_ntc.h'
R_NOM, T_NOM, BETA = 10000, 22.0, 3312.0
T_MIN, T_MAX, T_STEP = -25, 115, 5


def ohm(c):
    return R_NOM * math.exp(BETA * (1 / (c + 273.15) - 1 / (T_NOM + 273.15)))


def table():
    """(Ohm, C) pairs, Ohm rising, as one_latitude_table() needs."""
    return [(round(ohm(c)), c) for c in range(T_MAX, T_MIN - 1, -T_STEP)]


def header():
    pairs = table()
    rows = []
    for i in range(0, len(pairs), 4):
        rows.append('\t' + ' '.join('{%d, %d},' % p for p in pairs[i:i + 4]))
    return ('/* SPDX-License-Identifier: GPL-2.0 */\n'
            '/*\n'
            ' * Generated by tools/make-pocket-oz8806-ntc.py, do not edit.\n'
            ' * Cell NTC resistance (Ohm) to temperature (C) from the Beta formula:\n'
            ' * %d Ohm at %g C, Beta %g K, %d C steps.\n'
            ' */\n'
            '#ifndef OZ8806_NTC_H\n'
            '#define OZ8806_NTC_H\n\n'
            'static const struct oz8806_pair oz8806_ntc[%d] = {\n'
            '%s\n'
            '};\n\n'
            '#endif\n') % (R_NOM, T_NOM, BETA, T_STEP, len(pairs), '\n'.join(rows))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='compare with the header instead of writing it')
    ap.add_argument('--out', type=Path, default=OUT)
    a = ap.parse_args()
    text = header()
    if a.check:
        same = a.out.is_file() and a.out.read_text() == text
        print('%s %s' % (a.out, 'matches' if same else 'differs'))
        sys.exit(0 if same else 1)
    a.out.write_text(text)
    print('wrote %s, %d points' % (a.out, len(table())))


if __name__ == '__main__':
    main()
